/** { name, code } for an ICAO hex address, or null when unknown / non-ICAO. */
export function countryForHex(hex) {
  if (typeof hex !== 'string' || !/^[0-9a-f]{6}$/i.test(hex)) return null;
  const addr = parseInt(hex, 16);
  let lo = 0;
  let hi = RANGES.length - 1;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    const [start, end, name, code] = RANGES[mid];
    if (addr < start) hi = mid - 1;
    else if (addr > end) lo = mid + 1;
    else return { name, code };
  }
  return null;
}

/** Flag emoji from an ISO 3166 alpha-2 code. */
export function flagEmoji(code) {
  if (!/^[A-Z]{2}$/.test(code || '')) return '';
  return String.fromCodePoint(...[...code].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65));
}
